export const GHANA_REGION_NAMES: string[] = GHANA_REGIONS.map((r) => r.name);

export function districtsForRegion(regionName: string | null | undefined): string[] {
  if (!regionName) return [];
  const key = regionName.trim().toLowerCase();
  const region = GHANA_REGIONS.find((r) => r.name.toLowerCase() === key || r.code === key);
  return region ? region.districts : [];
}

export function isValidRegion(regionName: string | null | undefined): boolean {
  if (!regionName) return true;
  return districtsForRegion(regionName).length > 0;
}

/** A district is valid when it belongs to the supplied region. */
export function isValidDistrict(
  regionName: string | null | undefined,
  district: string | null | undefined,
): boolean {
  if (!district) return true;
  const list = districtsForRegion(regionName);
  return list.some((d) => d.toLowerCase() === district.trim().toLowerCase());
}

export const GHANA_DISTRICT_COUNT = GHANA_REGIONS.reduce((sum, r) => sum + r.districts.length, 0);
